#!/usr/bin/env node
// Regenerates lib/public/aigora/i18n/index.js: one import per namespace file in i18n/ko and i18n/en.
// Run after adding or removing a namespace file; the output is sorted, so a merge conflict is resolved by rerunning.
"use strict";
var fs = require("fs");
var path = require("path");

var DIR = path.join(__dirname, "..", "lib", "public", "aigora", "i18n");
var LANGS = ["ko", "en"];

function namespaces(lang) {
  return fs.readdirSync(path.join(DIR, lang)).filter(function (f) { return /\.js$/.test(f); }).map(function (f) { return f.slice(0, -3); }).sort();
}

function build() {
  var ids = {};
  LANGS.forEach(function (l) { namespaces(l).forEach(function (n) { ids[n] = true; }); });
  var all = Object.keys(ids).sort();
  var id = function (l, n) { return l + "_" + n.replace(/\W/g, "_"); };
  var out = ["// GENERATED by scripts/gen-i18n-index.js - do not edit; rerun the script after adding a namespace file.", ""];
  LANGS.forEach(function (l) { all.forEach(function (n) { out.push("import " + id(l, n) + ' from "./' + l + "/" + n + '.js";'); }); out.push(""); });
  out.push("export var DICTS = {");
  LANGS.forEach(function (l) {
    out.push("  " + l + ": Object.assign({}, " + all.map(function (n) { return id(l, n); }).join(", ") + "),");
  });
  out.push("};", "");
  return out.join("\n");
}

module.exports = { build: build, DIR: DIR };

if (require.main === module) {
  fs.writeFileSync(path.join(DIR, "index.js"), build());
  console.log("i18n/index.js written");
}
