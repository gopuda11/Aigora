// files found in node_modules. Run `npm ci` first, then `npm run gen:notices`.
// Usage: node scripts/gen-third-party-notices.js [--check]   (--check exits 1 when the committed file is stale)
"use strict";
var fs = require("fs");
var path = require("path");
var crypto = require("crypto");

var ROOT = path.join(__dirname, "..");
var OUT = path.join(ROOT, "THIRD-PARTY-NOTICES.md");

// License fields that are missing or not SPDX in the lockfile / package.json.
var LICENSE_OVERRIDE = { "qrcode-terminal": "Apache-2.0" };
// Copyright holders for packages that ship no license file (checked against their upstream repositories).
var COPYRIGHT_OVERRIDE = { "@openai/codex": "(c) OpenAI (https://github.com/openai/codex)" };
// Packages whose license is the vendor's own terms; their text is not reproduced.
var PROPRIETARY = /^node_modules\/@anthropic-ai\/claude-agent-sdk(-[a-z0-9-]+)?$/;

function readFirst(dir, names) {
  var files;
  try { files = fs.readdirSync(dir); } catch (e) { return null; }
  for (var i = 0; i < names.length; i++) {
    var hit = files.filter(function (f) { return f.toLowerCase().replace(/\.(md|txt)$/, "") === names[i]; })[0];
    if (hit) { try { return fs.readFileSync(path.join(dir, hit), "utf8").replace(/\r\n/g, "\n").trim(); } catch (e) { /* next */ } }
  }
  return null;
}

function authorOf(pkg) {
  var a = pkg.author;
  if (!a) return "";
  return typeof a === "string" ? a.replace(/\s*[<(].*$/, "").trim() : (a.name || "");
}

function copyrightOf(licenseText, pkg) {
  if (licenseText) {
    var m = licenseText.split("\n").filter(function (l) { return /^\s*(copyright\s*(\(c\)|©)?\s*\d|copyright\s*(\(c\)|©)|\(c\)\s*\d|©)/i.test(l); });
    if (m.length) return m.map(function (l) { return l.trim(); }).join(" ; ").slice(0, 200);
  }
  var a = authorOf(pkg);
  return a ? "(c) " + a + " (from package.json)" : "see package";
}

function collect() {
  var lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8"));
  var rows = [];
  Object.keys(lock.packages).forEach(function (key) {
    if (!key || lock.packages[key].dev) return;
    var entry = lock.packages[key];
    var name = key.replace(/^.*node_modules\//, "");
    var dir = path.join(ROOT, key);
    // Optional per-platform binary packages are only installed on the matching platform; read the base package instead so the
    // output does not depend on the machine that generates it.
    var base = key.replace(/-(darwin|linux|win32)-[a-z0-9-]+$/, "");
    if (!fs.existsSync(path.join(dir, "package.json")) && base !== key) dir = path.join(ROOT, base);
    var pkg = {};
    try { pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")); } catch (e) { /* optional platform package not installed here */ }
    var lic = LICENSE_OVERRIDE[name] || entry.license || (typeof pkg.license === "string" ? pkg.license : "") || "UNKNOWN";
    var proprietary = PROPRIETARY.test(key);
    var text = proprietary ? null : readFirst(dir, ["license", "licence", "copying"]);
    var notice = readFirst(dir, ["notice"]);
    rows.push({
      name: name, version: entry.version, license: proprietary ? "Anthropic terms (proprietary)" : lic,
      copyright: proprietary ? "(c) Anthropic PBC" : (COPYRIGHT_OVERRIDE[name.replace(/-(darwin|linux|win32)-[a-z0-9-]+$/, "")] || copyrightOf(text, pkg)),
      text: text, notice: notice, proprietary: proprietary, optional: !!entry.optional
    });
  });
  rows.sort(function (a, b) { return a.name < b.name ? -1 : a.name > b.name ? 1 : 0; });
  return rows;
}

