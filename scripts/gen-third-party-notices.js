function build() {
  var rows = collect();
  var out = [HEAD, SPECIAL];
  out.push("## Production dependencies", "", rows.length + " packages from `package-lock.json` (development-only packages are not listed).", "");
  out.push("| Package | Version | License | Copyright |", "| --- | --- | --- | --- |");
  rows.forEach(function (r) {
    out.push("| `" + r.name + "` | " + r.version + " | " + r.license + (r.optional ? " (optional)" : "") + " | " + r.copyright.replace(/\|/g, "/") + " |");
  });
  out.push("");
  var notices = rows.filter(function (r) { return r.notice; });
  if (notices.length) {
    out.push("## NOTICE files (Apache-2.0)", "");
    notices.forEach(function (r) { out.push("### " + r.name + " " + r.version, "", "```text", r.notice, "```", ""); });
  }
  var groups = {};
  rows.forEach(function (r) {
    if (!r.text) return;
    var h = crypto.createHash("sha1").update(r.text).digest("hex");
    (groups[h] = groups[h] || { text: r.text, names: [] }).names.push(r.name + "@" + r.version);
  });
  out.push("## License texts", "", "Packages with an identical license file share one entry.", "");
  Object.keys(groups).sort(function (a, b) { return groups[a].names[0] < groups[b].names[0] ? -1 : 1; }).forEach(function (h) {
    out.push("### " + groups[h].names.join(", "), "", "```text", groups[h].text, "```", "");
  });
  var noText = rows.filter(function (r) { return !r.text && !r.proprietary; });
  if (noText.length) {
    out.push("Packages that ship no license file in `node_modules` (license per their `package.json` / registry entry): " +
      noText.map(function (r) { return "`" + r.name + "` (" + r.license + ")"; }).join(", ") + ".", "");
  }
  out.push(STATIC_TAIL);
  return out.join("\n").replace(/\n{3,}/g, "\n\n").replace(/\s+$/, "") + "\n";
}

if (require.main === module) {
  var text = build();
  if (process.argv.indexOf("--check") !== -1) {
    var cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== text) { console.error("[gen-third-party-notices] THIRD-PARTY-NOTICES.md is stale; run npm run gen:notices"); process.exit(1); }
    console.log("[gen-third-party-notices] up to date");
  } else {
    fs.writeFileSync(OUT, text);
    console.log("[gen-third-party-notices] wrote " + path.relative(ROOT, OUT));
  }
}
module.exports = { build: build };
